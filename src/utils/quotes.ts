export function getQuoteForDate(date: Date): QuoteItem {
  // Generate deterministic day index based on year, month, day
  const year = date.getFullYear();
  const month = date.getMonth();
  const day = date.getDate();
  // Simple deterministic hash
  const dayNumber = year * 372 + month * 31 + day;
  const index = Math.abs(dayNumber) % DAILY_QUOTES.length;
  return DAILY_QUOTES[index];
}
